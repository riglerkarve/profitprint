#!/usr/bin/env node
/**
 * Daily briefing generator (Phase 4).
 *
 * Zero dependencies — plain Node. Run by .github/workflows/daily-briefing.yml on a
 * cron schedule (free on public repos), or locally:  node scripts/daily-briefing.mjs
 *
 * It:
 *   1. Reads the canonical data/metrics.json.
 *   2. Computes totals and the day-over-day movement (truthfully — 0 is 0).
 *   3. Writes reports/YYYY-MM-DD.md with the five sections the brief calls for.
 *   4. Regenerates dashboard/data.js so the dashboard stays in sync with metrics.
 *   5. Reads an optional reports/_activity.json so a human (or a future automation)
 *      can drop in "what shipped / what's next" notes; falls back to honest defaults.
 *
 * It never invents revenue. Manual-only sources are labeled as such.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const money = (n) => '$' + (Number(n) || 0).toFixed(2);
const read = (p, fb) => (existsSync(join(ROOT, p)) ? JSON.parse(readFileSync(join(ROOT, p), 'utf8')) : fb);

const metrics = read('data/metrics.json', null);
if (!metrics) { console.error('data/metrics.json not found'); process.exit(1); }

const today = new Date().toISOString().slice(0, 10);
const series = [...metrics.series].sort((a, b) => (a.date < b.date ? -1 : 1));
const sum = (arr, k) => arr.reduce((a, s) => a + (s[k] || 0), 0);

const revKeys = ['product_revenue', 'affiliate_commission', 'ad_revenue'];
const totalRev = revKeys.reduce((a, k) => a + sum(series, k), 0);

const last = series[series.length - 1] || {};
const prev = series[series.length - 2] || {};
const delta = (k) => (last[k] || 0) - (prev[k] || 0);
const arrow = (d) => (d > 0 ? `▲ +${d}` : d < 0 ? `▼ ${d}` : '→ 0');

const activity = read('reports/_activity.json', {});
const shipped = activity.shipped || [];
const wentWell = activity.wentWell || null;
const underperforming = activity.underperforming || null;
const nextPlan = activity.next || [];

const flaggedLimits = (metrics.freeTierLimits || []).filter((l) => !['ok', 'not-in-use'].includes(l.status));
const pendingSources = (metrics.sources || []).filter((s) => String(s.status).startsWith('pending'));

const milestones = metrics.milestones || {};
const pct = (t) => Math.min(100, (totalRev / t) * 100).toFixed(totalRev / t < 0.1 ? 1 : 0);

const md = `# Daily briefing — ${today}

_Auto-generated by \`scripts/daily-briefing.mjs\`. Numbers come straight from \`data/metrics.json\`; nothing is estimated or faked._

## What shipped / changed in the last 24h
${shipped.length ? shipped.map((s) => `- ${s}`).join('\n') : '- No tracked changes logged. (Add items to `reports/_activity.json` → `shipped[]` to record them.)'}

## Key metrics snapshot
| Metric | To date | Δ vs prev day |
|---|---|---|
| Total revenue | ${money(totalRev)} | ${arrow(revKeys.reduce((a, k) => a + delta(k), 0))} |
| Product revenue (Payhip) | ${money(sum(series, 'product_revenue'))} | ${arrow(delta('product_revenue'))} |
| Affiliate commission (Amazon) | ${money(sum(series, 'affiliate_commission'))} | ${arrow(delta('affiliate_commission'))} |
| Ad revenue (AdSense) | ${money(sum(series, 'ad_revenue'))} | ${arrow(delta('ad_revenue'))} |
| Affiliate clicks | ${sum(series, 'affiliate_clicks')} | ${arrow(delta('affiliate_clicks'))} |
| Tool + site visits | ${sum(series, 'tool_visits') + sum(series, 'site_visits')} | ${arrow(delta('tool_visits') + delta('site_visits'))} |

Milestone progress: first \$1 → **${pct(milestones.first_dollar || 1)}%**, first \$100 → **${pct(milestones.first_hundred || 100)}%**, first \$1,000 → **${pct(milestones.first_thousand || 1000)}%**.

${pendingSources.length ? `> Data still manual/pending for: ${pendingSources.map((s) => s.name).join(', ')} — these require the human checkpoints (account + payout setup) before numbers can move.` : ''}
${flaggedLimits.length ? `\n> ⚠️ Free-tier watch: ${flaggedLimits.map((l) => `${l.resource} (${l.status})`).join(', ')}.` : ''}

## One thing that went well
${wentWell || (totalRev > 0 ? `Revenue is above zero (${money(totalRev)} to date).` : 'Infrastructure is in place and $0 spend is holding — every project is built and ready to deploy at no cost.')}

## One thing that didn\'t work / is underperforming
${underperforming || (totalRev === 0 ? 'Revenue is still $0 — expected at this stage, but it stays the top risk. Nothing can sell until the account/payout human checkpoints are cleared and the sites are live and indexing.' : 'Nothing flagged today.')}

## Next 24–48h plan
${nextPlan.length ? nextPlan.map((s) => `- ${s}`).join('\n') : `- Clear the next open human checkpoint (see HUMAN_CHECKPOINTS.md).\n- Once live: confirm the calculator and content site are indexed and analytics is recording visits.\n- Draft the next guide to widen long-tail search coverage.`}

---
_Generated ${new Date().toISOString()}._
`;

if (!existsSync(join(ROOT, 'reports'))) mkdirSync(join(ROOT, 'reports'));
writeFileSync(join(ROOT, 'reports', `${today}.md`), md);

// Keep the dashboard's standalone data copy in sync with the canonical metrics.
const dataJs = `// AUTO-GENERATED from data/metrics.json by scripts/daily-briefing.mjs — do not hand-edit.\nwindow.PORTFOLIO_DATA = ${JSON.stringify(metrics, null, 2)};\n`;
writeFileSync(join(ROOT, 'dashboard', 'data.js'), dataJs);

console.log(`Wrote reports/${today}.md and refreshed dashboard/data.js`);
